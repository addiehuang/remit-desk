// Shared between tokens:build and tokens:check, so the generator and the
// parity check can never drift apart: there is only one implementation.
import { readFileSync } from 'node:fs';

export const SOURCE = 'tokens/figma-export.json';
export const TARGET = 'src/styles/tokens.css';

const PRIMITIVE = 'Primitive';
const SEMANTIC = 'Semantic';

// A semantic group maps to a Tailwind 4 theme namespace, which is what decides
// the utilities that exist: --color-surface gives bg-surface and text-surface,
// --spacing-md gives p-md and gap-md, and so on.
const NAMESPACE = { color: 'color', space: 'spacing', radius: 'radius', text: 'text' };

// Figma stores lengths as px because designers think in px. The web wants rem,
// so that a reader who raises their browser font size scales the layout with
// the text. One conversion, in one place.
const PX_PER_REM = 16;

const slug = (parts) =>
  parts.join('-').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

function leaves(node, path = [], out = []) {
  for (const [key, value] of Object.entries(node ?? {})) {
    if (!value || typeof value !== 'object') continue;
    if ('value' in value || '$alias' in value) out.push({ path: [...path, key], token: value });
    else leaves(value, [...path, key], out);
  }
  return out;
}

const primitiveName = (path) => `--p-${slug(path)}`;

// "{Primitive.slate/1}" -> ["slate", "1"]
function aliasTarget(alias, owner) {
  const inner = String(alias).replace(/^\{/, '').replace(/\}$/, '');
  const dot = inner.indexOf('.');
  if (dot === -1) throw new Error(`${owner}: alias "${alias}" has no collection prefix.`);
  const collection = inner.slice(0, dot);
  if (collection !== PRIMITIVE) {
    throw new Error(`${owner}: alias "${alias}" points at "${collection}". A semantic role must alias a primitive.`);
  }
  return inner.slice(dot + 1).split('/');
}

const length = (px) => (px === 0 ? '0' : `${Number((px / PX_PER_REM).toFixed(4))}rem`);

export function build(json) {
  const tokens = json.tokens;
  if (!tokens || !tokens[PRIMITIVE] || !tokens[SEMANTIC]) {
    throw new Error(`${SOURCE} must contain tokens.${PRIMITIVE} and tokens.${SEMANTIC}. Re-export both collections.`);
  }

  const primitives = [];
  const known = new Set();
  for (const { path, token } of leaves(tokens[PRIMITIVE])) {
    const name = primitiveName(path);
    if (token.value === undefined) throw new Error(`Primitive ${path.join('/')} has no value.`);
    primitives.push({ name, value: String(token.value) });
    known.add(name);
  }

  const semantic = [];
  for (const { path, token } of leaves(tokens[SEMANTIC])) {
    const owner = `Semantic ${path.join('/')}`;
    const [group, ...rest] = path;
    const ns = NAMESPACE[group];
    if (!ns) throw new Error(`${owner}: unknown group "${group}". Add it to NAMESPACE.`);
    if (rest.length === 0) throw new Error(`${owner}: a token needs a name below its group.`);
    const name = `--${ns}-${slug(rest)}`;

    let value;
    if (token.$alias !== undefined) {
      const target = primitiveName(aliasTarget(token.$alias, owner));
      if (!known.has(target)) throw new Error(`${owner}: alias "${token.$alias}" does not resolve to a primitive.`);
      value = `var(${target})`;
    } else if (token.type === 'color') {
      // The two layer split only holds if no semantic colour carries a raw value.
      throw new Error(`${owner}: a semantic colour must alias a primitive, not hold ${JSON.stringify(token.value)}.`);
    } else if (typeof token.value === 'number') {
      value = length(token.value);
    } else {
      throw new Error(`${owner}: cannot convert ${JSON.stringify(token.value)}.`);
    }
    semantic.push({ name, value });
  }

  const render = (list) =>
    list.slice().sort((a, b) => a.name.localeCompare(b.name)).map((t) => `  ${t.name}: ${t.value};`).join('\n');

  return [
    '/* Generated by pnpm tokens:build from tokens/figma-export.json. Do not edit. */',
    '',
    '/* Primitives. Deliberately outside @theme, so they define no utilities and',
    '   a component cannot reach past the semantic layer. */',
    ':root {',
    render(primitives),
    '}',
    '',
    '/* Semantic roles. @theme inline rather than @theme, because each value is a',
    '   var() pointing at a primitive and inline resolves it at build time. */',
    '@theme inline {',
    render(semantic),
    '}',
    ''
  ].join('\n');
}

export const readSource = () => JSON.parse(readFileSync(SOURCE, 'utf8'));

export function parseCss(css) {
  const map = new Map();
  for (const [, name, value] of css.matchAll(/(--[a-z0-9-]+)\s*:\s*([^;]+);/g)) map.set(name, value.trim());
  return map;
}
